import type { Metadata } from "next";
import { site } from "./site";

type PageMeta = {
  title: string;
  description: string;
  /** Path beginning with "/", used for the canonical URL. */
  path: string;
  noIndex?: boolean;
  /** Small label above the title on the share card. Defaults to the first path segment. */
  eyebrow?: string;
};

const EYEBROWS: Record<string, string> = {
  work: "Work",
  services: "Services",
  process: "Process",
  about: "About",
  careers: "Careers",
  faq: "FAQ",
  contact: "Start a project",
};

/** Share-card URL for /og (the Dot on the pyramid + the page title). */
export function ogImageUrl(title: string, eyebrow?: string) {
  const q = new URLSearchParams({ title });
  if (eyebrow) q.set("eyebrow", eyebrow);
  return `/og?${q.toString()}`;
}

/**
 * Unique title, description, canonical, Open Graph and share image for every page
 * (brief §11 SEO). Images are generated by app/og/route.tsx and feature the Dot.
 */
export function pageMetadata({ title, description, path, noIndex, eyebrow }: PageMeta): Metadata {
  const label = eyebrow ?? EYEBROWS[path.split("/")[1] ?? ""] ?? site.name;
  const image = {
    url: ogImageUrl(title, label),
    width: 1200,
    height: 630,
    alt: `${title} — ${site.name}`,
  };
  return {
    title,
    description,
    alternates: { canonical: path },
    openGraph: {
      title: `${title} — ${site.name}`,
      description,
      url: path,
      siteName: site.name,
      locale: site.locale,
      type: "website",
      images: [image],
    },
    twitter: {
      card: "summary_large_image",
      title: `${title} — ${site.name}`,
      description,
      images: [image.url],
    },
    ...(noIndex ? { robots: { index: false, follow: true } } : {}),
  };
}
